    public void load_pasien(){
        jComboBox1.removeAllItems();
        jComboBox1.addItem("-- Pilih Pasien --");
        
        try{
            conn = Koneksi.getConnection();
            Statement stat = conn.createStatement();
            
            String sql = "SELECT nama FROM pasien ORDER BY nama DESC";
            ResultSet res = stat.executeQuery(sql);
            
            while (res.next()){
                String nama = res.getString("nama");
                jComboBox1.addItem(nama);
            }
            
            res.close();
            stat.close();
        } catch (Exception e){
            JOptionPane.showMessageDialog(this, "Gagal memuat data pasien: " + e.getMessage());
            
        }
    }
    
