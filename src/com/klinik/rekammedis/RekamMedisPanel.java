    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow >= 0 && selectedRow < idList.size()) {
            selectedId = idList.get(selectedRow);

            // Isi ComboBox Pasien
            String namaPasien = jTable1.getValueAt(selectedRow, 1).toString();
            for (int i = 0; i < jComboBox1.getItemCount(); i++) {
                if (jComboBox1.getItemAt(i).equals(namaPasien)) {
                    jComboBox1.setSelectedIndex(i);
                    break;
                }
            }

            // Isi DateChooser
            try {
                java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
                java.util.Date tgl = sdf.parse(jTable1.getValueAt(selectedRow, 2).toString());
                jDateChooser1.setDate(tgl);
            } catch (Exception ex) {
                jDateChooser1.setDate(null);
            }

            // Isi TextArea Diagnosis & Catatan
            jTextArea1.setText(jTable1.getValueAt(selectedRow, 3).toString());
            jTextArea2.setText(jTable1.getValueAt(selectedRow, 4).toString());
        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if(jComboBox1.getSelectedIndex() == 0){
            JOptionPane.showMessageDialog(this, "Silahkan pilih nama pasien terlebih dahulu!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if(jDateChooser1.getDate() == null){
            JOptionPane.showMessageDialog(this, "Silahkan pilih tanggal pemeriksaan", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try{
            String nama_pasien = jComboBox1.getSelectedItem().toString();
            
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            String tanggal = sdf.format(jDateChooser1.getDate());
            
            String diagnosis = jTextArea1.getText();
            String catatan = jTextArea2.getText();
            
            Connection conn = Koneksi.getConnection();
            
            int pasienId=0;
            
            String queryCariId="SELECT id FROM pasien WHERE nama = ?";
            PreparedStatement psCari = conn.prepareStatement(queryCariId);
            psCari.setString(1, nama_pasien);
            ResultSet rsCari = psCari.executeQuery();
            
            if (rsCari.next()){
                pasienId = rsCari.getInt("id");
            }
            rsCari.close();
            psCari.close();
            
            if (pasienId == 0){
                JOptionPane.showMessageDialog(this, "Data pasien tidak ada di database!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            String sql = "INSERT INTO rekam_medis (pasien_id, tanggal_kunjungan, diagnosis, catatan) VALUES (?, ?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);
            
            ps.setInt(1, pasienId);
            ps.setString(2, tanggal);
            ps.setString(3, diagnosis);
            ps.setString(4, catatan);
            
            int hasil = ps.executeUpdate();
            
            if(hasil > 0){
                JOptionPane.showMessageDialog(this, "Data rekam medis berhasil disimpan");
                bersihkanForm();
                loadTable();
            }
            ps.close();
        } catch (Exception e){
            JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

